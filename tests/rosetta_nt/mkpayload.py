#!/usr/bin/env python3
"""mkpayload.py — embed payload.dylib's __TEXT as a C blob for ntstub.c.

 python3 mkpayload.py payload.dylib payload_blob.h

ntstub flat-copies __TEXT into a MAP_TRANSLATED_ALLOW_EXECUTE region at the
same relative layout (vmaddr 0), so the payload's PC-relative static access
survives unchanged; the dylib is verified fixup/reloc-free at build time
(dyld_info -fixups, otool -r), which is what makes that safe. __DATA is pure
zero-fill here (all payload statics are bss), so the anon mapping supplies it.
Emits the symbol offsets plus each entry's first instruction word, which
ntstub readback-verifies after mapping — a changed artifact fails closed.
"""
import re
import subprocess
import sys

DYLIB = sys.argv[1] if len(sys.argv) > 1 else "payload.dylib"
OUT = sys.argv[2] if len(sys.argv) > 2 else "payload_blob.h"

# fixups/relocs must be empty: anything here would need applying after the
# flat copy, which we do not do
fix = subprocess.run(["dyld_info", "-fixups", DYLIB], capture_output=True, text=True).stdout
if fix.splitlines()[3:]:  # rows under the "segment section address type target" header
    raise SystemExit("payload has dyld fixups — add no pointer-valued statics")
rel = subprocess.run(["otool", "-r", DYLIB], capture_output=True, text=True).stdout
if len([l for l in rel.splitlines() if l.strip()]) > 1:
    raise SystemExit("payload has relocations")

# r13: the append stub saves x0-x18/x30 only. Any FP/SIMD use in the payload
# clobbers q-registers Rosetta holds live across the 0x18a0 call (and, in the
# converters, guest XMM state) — it crashed steam.exe on chain arming. Build
# with -mgeneral-regs-only; this gate refuses a payload that slipped.
asm = subprocess.check_output(["otool", "-tv", DYLIB], text=True)
simd = [l for l in asm.splitlines() if re.search(r"\b[qvdsbh][0-9]{1,2}\b", l.split("\t", 1)[-1])]
if simd:
    raise SystemExit("payload uses FP/SIMD registers (build with -mgeneral-regs-only):\n  "
                     + "\n  ".join(simd[:5]))

segs = []
out = subprocess.check_output(["otool", "-l", DYLIB], text=True).splitlines()
cur = None
for line in out:
    m = re.match(r"\s*segname (\S+)", line)
    if m:
        cur = m.group(1)
    m = re.match(r"\s*vmaddr (0x[0-9a-f]+)", line)
    if m and cur:
        addr = int(m.group(1), 16)
    m = re.match(r"\s*vmsize (0x[0-9a-f]+)", line)
    if m and cur:
        segs.append((cur, addr, int(m.group(1), 16)))
text = [s for s in segs if s[0] == "__TEXT"]
data = [s for s in segs if s[0] == "__DATA"]
if len(text) != 1 or len(data) != 1:
    raise SystemExit("expected exactly one __TEXT and one __DATA")
if data[0][2] > 0x4000:
    raise SystemExit("__DATA grew beyond one 16K unit — extend the mapper first")
span = data[0][1] + data[0][2] - text[0][1]  # whole image span

syms = {}
for line in subprocess.check_output(["nm", "-n", DYLIB], text=True).splitlines():
    cols = line.split()
    if len(cols) == 3 and cols[2].startswith("_ntfix_"):
        syms[cols[2][1:]] = int(cols[0], 16)

blob = open(DYLIB, "rb").read(0x4000)  # __TEXT filesize == vmsize == 0x4000
if len(blob) != 0x4000:
    raise SystemExit("short __TEXT read")
words = [int.from_bytes(blob[i:i + 4], "little") for i in range(0, len(blob), 4)]

with open(OUT, "w") as f:
    f.write("/* generated by mkpayload.py from payload.dylib — do not edit */\n")
    f.write("#include <stdint.h>\n")
    f.write(f"#define PAYLOAD_SPAN {span}u\n")
    for name in ("ntfix_init", "ntfix_append", "ntfix_compose", "ntfix_decompose"):
        if name not in syms:
            raise SystemExit(f"symbol {name} missing")
        off = syms[name]
        f.write(f"#define P_{name.upper()}_OFF {off}u\n")
        f.write(f"#define P_{name.upper()}_W0 0x{words[off // 4]:08x}u\n")
    f.write(f"#define PAYLOAD_TEXT_WORDS {len(words)}u\n")
    f.write("static const uint32_t payload_text[PAYLOAD_TEXT_WORDS] = {\n")
    for i in range(0, len(words), 8):
        f.write("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",\n")
    f.write("};\n")
print(f"{OUT}: __TEXT {len(words)} words, span {span:#x}, "
      + ", ".join(f"{k}@{v:#x}" for k, v in sorted(syms.items())))
