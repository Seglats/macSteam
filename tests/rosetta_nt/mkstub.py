#!/usr/bin/env python3
"""mkstub.py — flatten a stub .o's __TEXT into a C blob header for ntstub.c.

 clang -arch arm64 -c -o stub.o stub.S && python3 mkstub.py stub.o stub_blob.h
 clang -arch arm64 -c -o appendstub.o appendstub.S && \
     python3 mkstub.py appendstub.o append_blob.h _append_stub,pcall,pback

Optional third argument: comma-separated symbol list (default = the legacy
r1-r3 stub profile). Emits <SYM>_OFF defines (word offsets from the first
symbol) and the blob; ntstub.c patches any placeholder quads by value.
"""

import re
import subprocess
import sys

OBJ = sys.argv[1] if len(sys.argv) > 1 else "stub.o"
OUT = sys.argv[2] if len(sys.argv) > 2 else "stub_blob.h"
SYMS = (sys.argv[3].split(",") if len(sys.argv) > 3 else
        ["_stub_popf_pure", "_stub_pushf_pure", "_stub_popf_entry", "_stub_pushf_entry",
         "pdword_popf", "pback_popf", "pdword_pushf", "pback_pushf",
         "ctr_popf", "ctr_pushf"])


def section_bytes(path):
    out = subprocess.check_output(["otool", "-X", "-s", "__TEXT", "__text", path], text=True)
    data = bytearray()
    for line in out.splitlines():
        parts = line.split()
        if parts and re.fullmatch(r"[0-9a-f]+", parts[0]) and len(parts) > 1:
            for h in parts[1:]:
                if re.fullmatch(r"[0-9a-f]{2,8}", h):
                    b = bytes.fromhex(h.rjust(8 if len(h) > 2 else 2, "0")[-8:] if len(h) > 2 else h)
                    if len(h) > 2:  # otool words are big-endian per 4-byte group
                        b = b[::-1]
                    data += b
    return bytes(data)


def symbol(path, name):
    out = subprocess.check_output(["nm", "-n", path], text=True)
    for line in out.splitlines():
        cols = line.split()
        if len(cols) == 3 and cols[2] == name:
            return int(cols[0], 16)
    raise SystemExit(f"symbol {name} not found in {path}")


blob = section_bytes(OBJ)
if len(blob) % 4:
    raise SystemExit(f"__text size {len(blob)} not a multiple of 4")
base = min(symbol(OBJ, s) for s in SYMS)
words = [int.from_bytes(blob[i:i + 4], "little") for i in range(0, len(blob), 4)]
off = lambda name: (symbol(OBJ, name) - base) // 4

with open(OUT, "w") as f:
    f.write("/* generated by mkstub.py — do not edit */\n")
    f.write("#include <stdint.h>\n")
    f.write(f"#define STUB_LEN {len(words)}u\n")
    for s in SYMS:
        f.write(f"#define {s.upper().lstrip('_')}_OFF {off(s)}u\n")
    f.write("static const uint32_t stub_blob[STUB_LEN] = {\n")
    for i in range(0, len(words), 6):
        f.write("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 6]) + ",\n")
    f.write("};\n")
print(f"{OUT}: {len(words)} words, " + ", ".join(f"{s}@{off(s)}" for s in SYMS))
